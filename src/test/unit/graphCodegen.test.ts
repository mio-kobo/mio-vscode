import * as assert from 'node:assert/strict';
import { formatExpression } from '../../graph/codegen/generateSource';
import {
  compileMioGraphValue,
  type GraphCompilationResult,
} from '../../graph/compiler';
import { formatMioLiteral } from '../../graph/model/literals';
import type { IrExpression } from '../../graph/ir/ir';
import {
  GraphBuilder,
  functionGraph,
  programGraph,
  type RawGraphDefinition,
} from './graphFixtures';

function compile(raw: RawGraphDefinition): GraphCompilationResult {
  return compileMioGraphValue(raw);
}

function compileOk(raw: RawGraphDefinition): GraphCompilationResult {
  const result = compile(raw);
  assert.equal(
    result.ok,
    true,
    result.diagnostics.map((item) => `${item.code}: ${item.message}`).join('; '),
  );
  assert.ok(result.source);
  return result;
}

function compileFails(raw: RawGraphDefinition, code: string): GraphCompilationResult {
  const result = compile(raw);
  assert.equal(result.ok, false);
  assert.equal(result.source, undefined);
  assert.ok(
    result.diagnostics.some((item) => item.code === code),
    `expected ${code}, got ${result.diagnostics
      .map((item) => item.code)
      .join(', ')}`,
  );
  return result;
}

function header(graphId: string): string {
  return `${[
    '// Generated by Mio Graph. Do not edit this file by hand.',
    `// Graph: ${graphId} (version 1)`,
    '',
  ].join('\n')}\n`;
}

const literal = (value: number, type: 'int64' | 'float64' = 'int64'): IrExpression => ({
  kind: 'literal',
  literal: value,
  type,
});

const binary = (
  operator: string,
  left: IrExpression,
  right: IrExpression,
  type: 'int64' | 'bool' = 'int64',
): IrExpression => ({
  kind: 'binary',
  operator,
  left,
  right,
  type,
});

suite('Mio Graph code generation', () => {
  test('generates constants, arithmetic and a function call', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('add', 'Add')
      .node('ten', 'Constant', { type: 'int64', value: 10 })
      .node('twenty', 'Constant', { type: 'int64', value: 20 })
      .node('chant', 'FunctionCall', { function: 'chant' })
      .node('read', 'VariableGet', { variable: 'r' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('e2', 'set', 'exec_out', 'chant', 'exec_in')
      .connect('d1', 'add', 'result', 'set', 'value')
      .connect('d2', 'ten', 'value', 'add', 'a')
      .connect('d3', 'twenty', 'value', 'add', 'b')
      .connect('d4', 'read', 'value', 'chant', 'arg_0');

    const result = compileOk(builder.build());
    assert.equal(
      result.source,
      `${header('program')}waza mio_graph_main() -> unit {
    kaku r: int64 = 0;
    r = 10 + 20;
    chant(r);
}

mio_graph_main();
`,
    );
  });

  test('materializes a pure expression with fan-out greater than one', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('add_inner', 'Add')
      .node('mul', 'Multiply')
      .node('add_outer', 'Add')
      .node('one', 'Constant', { type: 'int64', value: 1 })
      .node('two', 'Constant', { type: 'int64', value: 2 })
      .node('three', 'Constant', { type: 'int64', value: 3 });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'add_outer', 'result', 'set', 'value')
      .connect('d2', 'add_inner', 'result', 'add_outer', 'a')
      .connect('d3', 'mul', 'result', 'add_outer', 'b')
      .connect('d4', 'add_inner', 'result', 'mul', 'a')
      .connect('d5', 'three', 'value', 'mul', 'b')
      .connect('d6', 'one', 'value', 'add_inner', 'a')
      .connect('d7', 'two', 'value', 'add_inner', 'b');

    const result = compileOk(builder.build());
    assert.equal(
      result.source,
      `${header('program')}waza mio_graph_main() -> unit {
    kaku r: int64 = 0;
    kaku __mio_graph_t0: int64 = 1 + 2;
    r = __mio_graph_t0 + __mio_graph_t0 * 3;
}

mio_graph_main();
`,
    );
  });

  test('orders statements by exec connections, not by node array order', () => {
    const builder = new GraphBuilder()
      .variable('first', 'int64', 0)
      .variable('second', 'int64', 0)
      .node('set_second', 'VariableSet', { variable: 'second' })
      .node('set_first', 'VariableSet', { variable: 'first' })
      .node('entry', 'Entry', { name: 'mio_graph_main' })
      .node('one', 'Constant', { type: 'int64', value: 1 })
      .node('two', 'Constant', { type: 'int64', value: 2 });
    builder
      .connect('e1', 'entry', 'exec_out', 'set_first', 'exec_in')
      .connect('e2', 'set_first', 'exec_out', 'set_second', 'exec_in')
      .connect('d1', 'one', 'value', 'set_first', 'value')
      .connect('d2', 'two', 'value', 'set_second', 'value');

    const result = compileOk(builder.build());
    const firstIndex = result.source?.indexOf('first = 1;') ?? -1;
    const secondIndex = result.source?.indexOf('second = 2;') ?? -1;
    assert.ok(firstIndex >= 0 && secondIndex >= 0);
    assert.ok(firstIndex < secondIndex, 'exec order must win over array order');
  });

  test('generates if/else from a Branch node', () => {
    const builder = programGraph()
      .node('branch', 'Branch')
      .node('condition', 'Constant', { type: 'bool', value: true })
      .node('yes', 'FunctionCall', { function: 'chant' })
      .node('no', 'FunctionCall', { function: 'chant' })
      .node('yes_text', 'Constant', { type: 'string', value: 'yes' })
      .node('no_text', 'Constant', { type: 'string', value: 'no' });
    builder
      .connect('e1', 'entry', 'exec_out', 'branch', 'exec_in')
      .connect('d0', 'condition', 'value', 'branch', 'condition')
      .connect('t1', 'branch', 'true', 'yes', 'exec_in')
      .connect('f1', 'branch', 'false', 'no', 'exec_in')
      .connect('d1', 'yes_text', 'value', 'yes', 'arg_0')
      .connect('d2', 'no_text', 'value', 'no', 'arg_0');

    const result = compileOk(builder.build());
    assert.equal(
      result.source,
      `${header('program')}waza mio_graph_main() -> unit {
    kaku r: int64 = 0;
    moshi (hai) {
        chant("yes");
    } sore {
        chant("no");
    }
}

mio_graph_main();
`,
    );
  });

  test('omits sore when the false branch is empty', () => {
    const builder = programGraph()
      .node('branch', 'Branch')
      .node('condition', 'Constant', { type: 'bool', value: false })
      .node('yes', 'FunctionCall', { function: 'chant' })
      .node('text', 'Constant', { type: 'string', value: 'only' });
    builder
      .connect('e1', 'entry', 'exec_out', 'branch', 'exec_in')
      .connect('d0', 'condition', 'value', 'branch', 'condition')
      .connect('t1', 'branch', 'true', 'yes', 'exec_in')
      .connect('d1', 'text', 'value', 'yes', 'arg_0');

    const result = compileOk(builder.build());
    assert.ok(result.source?.includes('    moshi (iie) {\n        chant("only");\n    }\n'));
    assert.equal(result.source?.includes('sore'), false);
  });

  test('executes Sequence outputs in pin order regardless of connection order', () => {
    const builder = new GraphBuilder()
      .variable('first', 'int64', 0)
      .variable('second', 'int64', 0)
      .node('entry', 'Entry', { name: 'mio_graph_main' })
      .node('sequence', 'Sequence', { branches: 3 })
      .node('set_first', 'VariableSet', { variable: 'first' })
      .node('set_second', 'VariableSet', { variable: 'second' })
      .node('chant', 'FunctionCall', { function: 'chant' })
      .node('one', 'Constant', { type: 'int64', value: 1 })
      .node('two', 'Constant', { type: 'int64', value: 2 })
      .node('done', 'Constant', { type: 'string', value: 'done' });
    builder
      .connect('e1', 'entry', 'exec_out', 'sequence', 'exec_in')
      .connect('e2', 'sequence', 'then_2', 'chant', 'exec_in')
      .connect('e3', 'sequence', 'then_1', 'set_second', 'exec_in')
      .connect('e4', 'sequence', 'then_0', 'set_first', 'exec_in')
      .connect('d1', 'one', 'value', 'set_first', 'value')
      .connect('d2', 'two', 'value', 'set_second', 'value')
      .connect('d3', 'done', 'value', 'chant', 'arg_0');

    const result = compileOk(builder.build());
    const source = result.source ?? '';
    assert.ok(source.indexOf('first = 1;') < source.indexOf('second = 2;'));
    assert.ok(source.indexOf('second = 2;') < source.indexOf('chant("done");'));
  });

  test('generates a function graph with parameters and a return value', () => {
    const builder = new GraphBuilder()
      .id('square')
      .kind('function')
      .node('entry', 'Entry', {
        name: 'square',
        returnType: 'int64',
        parameters: [{ name: 'value', type: 'int64' }],
      })
      .node('mul', 'Multiply')
      .node('return', 'Return');
    builder
      .connect('e1', 'entry', 'exec_out', 'return', 'exec_in')
      .connect('d1', 'entry', 'param_0', 'mul', 'a')
      .connect('d2', 'entry', 'param_0', 'mul', 'b')
      .connect('d3', 'mul', 'result', 'return', 'value');

    const result = compileOk(builder.build());
    assert.equal(
      result.source,
      `${header('square')}waza square(value: int64) -> int64 {
    kaesu value * value;
}
`,
    );
  });

  test('supports Return inside a program graph', () => {
    const builder = programGraph().node('return', 'Return');
    builder.connect('e1', 'entry', 'exec_out', 'return', 'exec_in');
    const result = compileOk(builder.build());
    assert.ok(result.source?.includes('    kaesu;\n}'));
    assert.ok(result.source?.endsWith('mio_graph_main();\n'));
  });

  test('reuses one temp for an exec-anchored function call', () => {
    const builder = new GraphBuilder()
      .variable('left', 'int64', 0)
      .variable('right', 'int64', 0)
      .node('entry', 'Entry', { name: 'mio_graph_main' })
      .node('call', 'FunctionCall', { function: 'p.answer' })
      .node('set_left', 'VariableSet', { variable: 'left' })
      .node('set_right', 'VariableSet', { variable: 'right' })
      .functionSignature({
        name: 'p.answer',
        parameters: [],
        returnType: 'int64',
      });
    builder
      .connect('e1', 'entry', 'exec_out', 'call', 'exec_in')
      .connect('e2', 'call', 'exec_out', 'set_left', 'exec_in')
      .connect('e3', 'set_left', 'exec_out', 'set_right', 'exec_in')
      .connect('d1', 'call', 'result', 'set_left', 'value')
      .connect('d2', 'call', 'result', 'set_right', 'value');

    const result = compileOk(builder.build());
    const source = result.source ?? '';
    assert.equal(
      (source.match(/kaku __mio_graph_t0: int64 = p\.answer\(\);/gu) ?? [])
        .length,
      1,
    );
    assert.ok(source.includes('left = __mio_graph_t0;'));
    assert.ok(source.includes('right = __mio_graph_t0;'));
  });

  test('uses pin default values when an input is unconnected', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node(
        'add',
        'Add',
        { dataType: 'int64' },
        { x: 0, y: 0 },
      )
      .node('two', 'Constant', { type: 'int64', value: 2 });
    const raw = builder.build();
    const add = raw.nodes.find((node) => node.id === 'add');
    assert.ok(add);
    add.pins = [{ id: 'add.a', defaultValue: 5 }];
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'two', 'value', 'add', 'b')
      .connect('d2', 'add', 'result', 'set', 'value');

    const result = compileOk(builder.build());
    assert.ok(result.source?.includes('r = 5 + 2;'));
  });

  test('generates deterministic output and a source map', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('one', 'Constant', { type: 'int64', value: 1 })
      .node('chant', 'FunctionCall', { function: 'chant' })
      .node('read', 'VariableGet', { variable: 'r' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('e2', 'set', 'exec_out', 'chant', 'exec_in')
      .connect('d1', 'one', 'value', 'set', 'value')
      .connect('d2', 'read', 'value', 'chant', 'arg_0');

    const first = compileOk(builder.build());
    const second = compileOk(builder.build());
    assert.equal(first.source, second.source);
    assert.deepEqual(first.sourceMap, second.sourceMap);

    const map = first.sourceMap;
    assert.ok(map);
    assert.equal(map?.graphId, 'program');
    const setEntry = map?.entries.find((entry) => entry.nodeId === 'set');
    assert.deepEqual(setEntry, { nodeId: 'set', startLine: 6, endLine: 6 });
    const chantEntry = map?.entries.find((entry) => entry.nodeId === 'chant');
    assert.deepEqual(chantEntry, { nodeId: 'chant', startLine: 7, endLine: 7 });
  });

  test('formats literals using real Mio lexical rules', () => {
    assert.equal(formatMioLiteral('int64', 42), '42');
    assert.equal(formatMioLiteral('uint32', 4294967295), '4294967295');
    assert.equal(formatMioLiteral('float64', 1), '1.0');
    assert.equal(formatMioLiteral('float64', 0.30000000000000004), '0.30000000000000004');
    assert.equal(formatMioLiteral('float64', 1e-7), '1e-7');
    assert.equal(formatMioLiteral('float64', -0), '-0.0');
    assert.equal(formatMioLiteral('float32', 0.1), '0.1');
    assert.equal(formatMioLiteral('float32', 1e38), '1e+38');
    assert.equal(formatMioLiteral('bool', true), 'hai');
    assert.equal(formatMioLiteral('bool', false), 'iie');
    assert.equal(
      formatMioLiteral('string', 'a"b\\c\nd\te'),
      '"a\\"b\\\\c\\nd\\te"',
    );
  });

  test('formats nested expressions with correct grouping', () => {
    assert.equal(
      formatExpression(binary('+', binary('+', literal(1), literal(2)), literal(3))),
      '1 + 2 + 3',
    );
    assert.equal(
      formatExpression(binary('+', literal(1), binary('+', literal(2), literal(3)))),
      '1 + (2 + 3)',
    );
    assert.equal(
      formatExpression(binary('*', binary('+', literal(1), literal(2)), literal(3))),
      '(1 + 2) * 3',
    );
    assert.equal(
      formatExpression(binary('-', literal(1), binary('-', literal(2), literal(3)))),
      '1 - (2 - 3)',
    );
    assert.equal(
      formatExpression({
        kind: 'unary',
        operator: '!',
        operand: binary('==', literal(1), literal(2), 'bool'),
        type: 'bool',
      }),
      '!(1 == 2)',
    );
    assert.equal(
      formatExpression({
        kind: 'unary',
        operator: '!',
        operand: { kind: 'variable', name: 'flag', type: 'bool' },
        type: 'bool',
      }),
      '!flag',
    );
    assert.equal(
      formatExpression({
        kind: 'call',
        name: 'chant',
        arguments: [literal(1)],
        type: 'unit',
      }),
      'chant(1)',
    );
  });

  test('rejects evaluation-order and sharing mistakes with clear errors', () => {
    // 同一内联纯函数调用结果被使用两次，会在读取位置重复求值。
    const builder = programGraph()
      .node('call', 'FunctionCall', { function: 'p.value' })
      .node('add', 'Add', { dataType: 'int64' })
      .node('set', 'VariableSet', { variable: 'r' })
      .functionSignature({ name: 'p.value', parameters: [], returnType: 'int64' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'call', 'result', 'add', 'a')
      .connect('d2', 'call', 'result', 'add', 'b')
      .connect('d3', 'add', 'result', 'set', 'value');
    compileFails(builder.build(), 'MIOG3008');
  });

  test('rejects using a call result before its exec position', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('call', 'FunctionCall', { function: 'p.value' })
      .functionSignature({ name: 'p.value', parameters: [], returnType: 'int64' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('e2', 'set', 'exec_out', 'call', 'exec_in')
      .connect('d1', 'call', 'result', 'set', 'value');
    compileFails(builder.build(), 'MIOG3007');
  });

  test('rejects using a call result across exclusive branches', () => {
    const builder = programGraph()
      .node('branch', 'Branch')
      .node('condition', 'Constant', { type: 'bool', value: true })
      .node('call', 'FunctionCall', { function: 'p.value' })
      .node('set', 'VariableSet', { variable: 'r' })
      .node('return', 'Return')
      .node('return_else', 'Return')
      .functionSignature({ name: 'p.value', parameters: [], returnType: 'int64' });
    builder
      .connect('e1', 'entry', 'exec_out', 'branch', 'exec_in')
      .connect('d0', 'condition', 'value', 'branch', 'condition')
      .connect('t1', 'branch', 'true', 'call', 'exec_in')
      .connect('t2', 'call', 'exec_out', 'return', 'exec_in')
      .connect('f1', 'branch', 'false', 'set', 'exec_in')
      .connect('f2', 'set', 'exec_out', 'return_else', 'exec_in')
      .connect('d1', 'call', 'result', 'set', 'value');
    compileFails(builder.build(), 'MIOG3012');
  });

  test('requires unit calls to be on the exec flow', () => {
    const builder = programGraph()
      .node('chant', 'FunctionCall', { function: 'chant' })
      .node('text', 'Constant', { type: 'string', value: 'hello' });
    builder.connect('d1', 'text', 'value', 'chant', 'arg_0');
    compileFails(builder.build(), 'MIOG3009');
  });

  test('rejects variables without an initializer', () => {
    const builder = new GraphBuilder()
      .variable('uninitialized', 'int64')
      .node('entry', 'Entry', { name: 'mio_graph_main' });
    compileFails(builder.build(), 'MIOG0017');
  });

  test('rejects string literals Mio cannot represent', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('text', 'Constant', { type: 'string', value: 'bell\u0007' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'text', 'value', 'set', 'value');
    const result = compile(builder.build());
    assert.equal(result.ok, false);
    assert.ok(result.diagnostics.some((item) => item.code === 'MIOG0015'));
  });

  test('rejects unpaired UTF-16 surrogates in strings', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('text', 'Constant', { type: 'string', value: 'broken\ud800' });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'text', 'value', 'set', 'value');
    const result = compile(builder.build());
    assert.equal(result.ok, false);
    assert.ok(result.diagnostics.some((item) => item.code === 'MIOG0015'));
  });

  test('rejects out-of-range integer literals', () => {
    const builder = programGraph()
      .node('set', 'VariableSet', { variable: 'r' })
      .node('small', 'Constant', { type: 'int8', value: 300 });
    builder
      .connect('e1', 'entry', 'exec_out', 'set', 'exec_in')
      .connect('d1', 'small', 'value', 'set', 'value');
    const result = compile(builder.build());
    assert.equal(result.ok, false);
    assert.ok(result.diagnostics.some((item) => item.code === 'MIOG0015'));
  });

  test('accepts a unit function graph without an explicit Return', () => {
    const builder = functionGraph('announce', 'unit')
      .node('chant', 'FunctionCall', { function: 'chant' })
      .node('text', 'Constant', { type: 'string', value: 'hi' });
    builder
      .connect('e1', 'entry', 'exec_out', 'chant', 'exec_in')
      .connect('d1', 'text', 'value', 'chant', 'arg_0');
    const result = compileOk(builder.build());
    assert.equal(
      result.source,
      `${header('announce')}waza announce() -> unit {
    chant("hi");
}
`,
    );
  });
});
