// Graph IR -> Mio 源码。
// 这里只负责格式化与优先级处理；执行顺序、临时变量和类型都已由分析阶段决定。

import { formatMioLiteral } from '../model/literals';
import type {
  IrExpression,
  IrProgram,
  IrSourceMap,
  IrStatement,
} from '../ir/ir';
import { MioCodeWriter } from './codeWriter';

export const MIO_GRAPH_GENERATED_MARKER = '// Generated by Mio Graph';

const BINARY_PRECEDENCE: Record<string, number | undefined> = {
  '||': 1,
  '&&': 2,
  '==': 3,
  '!=': 3,
  '<': 4,
  '<=': 4,
  '>': 4,
  '>=': 4,
  '+': 5,
  '-': 5,
  '*': 6,
  '/': 6,
};

const UNARY_PRECEDENCE = 7;
const ATOM_PRECEDENCE = 8;

export interface GenerateSourceResult {
  source: string;
  sourceMap: IrSourceMap;
}

export function generateMioSource(program: IrProgram): GenerateSourceResult {
  const writer = new MioCodeWriter();
  const sourceMap: IrSourceMap = { graphId: program.graphId, entries: [] };

  writer.line(`${MIO_GRAPH_GENERATED_MARKER}. Do not edit this file by hand.`);
  writer.line(`// Graph: ${program.graphId} (version ${program.graphVersion})`);
  writer.pushBlankLine();

  for (const importPath of program.imports) {
    writer.line(`yobu "${importPath}";`);
  }
  if (program.imports.length > 0) {
    writer.pushBlankLine();
  }

  const parameters = program.parameters
    .map((parameter) => `${parameter.name}: ${parameter.type}`)
    .join(', ');
  writer.line(
    `waza ${program.functionName}(${parameters}) -> ${program.returnType} {`,
  );
  writer.pushIndent();
  emitStatements(program.body, writer, sourceMap);
  writer.popIndent();
  writer.line('}');

  if (program.emitEntryCall) {
    writer.pushBlankLine();
    writer.line(`${program.functionName}();`);
  }

  // 按生成行排序，便于编辑器直接二分查找；排序键完全确定。
  sourceMap.entries.sort((left, right) => {
    if (left.startLine !== right.startLine) {
      return left.startLine - right.startLine;
    }
    if (left.endLine !== right.endLine) {
      return left.endLine - right.endLine;
    }
    return left.nodeId < right.nodeId ? -1 : left.nodeId > right.nodeId ? 1 : 0;
  });
  return { source: writer.toString(), sourceMap };
}

function emitStatements(
  statements: readonly IrStatement[],
  writer: MioCodeWriter,
  sourceMap: IrSourceMap,
): void {
  for (const statement of statements) {
    emitStatement(statement, writer, sourceMap);
  }
}

function emitStatement(
  statement: IrStatement,
  writer: MioCodeWriter,
  sourceMap: IrSourceMap,
): void {
  const startLine = writer.nextLineNumber();
  switch (statement.kind) {
    case 'declare':
      writer.line(
        `kaku ${statement.name}: ${statement.type} = ${formatExpression(statement.expression)};`,
      );
      break;
    case 'assign':
      writer.line(
        `${statement.name} = ${formatExpression(statement.expression)};`,
      );
      break;
    case 'expression':
      writer.line(`${formatExpression(statement.expression)};`);
      break;
    case 'return':
      writer.line(
        statement.expression === undefined
          ? 'kaesu;'
          : `kaesu ${formatExpression(statement.expression)};`,
      );
      break;
    case 'if': {
      writer.line(`moshi (${formatExpression(statement.condition)}) {`);
      writer.pushIndent();
      emitStatements(statement.then, writer, sourceMap);
      writer.popIndent();
      if (statement.otherwise.length > 0) {
        writer.line('} sore {');
        writer.pushIndent();
        emitStatements(statement.otherwise, writer, sourceMap);
        writer.popIndent();
        writer.line('}');
      } else {
        writer.line('}');
      }
      break;
    }
  }
  const endLine = writer.nextLineNumber() - 1;
  if (statement.nodeId !== undefined) {
    sourceMap.entries.push({
      nodeId: statement.nodeId,
      startLine,
      endLine,
    });
  }
}

export function formatExpression(expression: IrExpression): string {
  switch (expression.kind) {
    case 'literal':
      return formatMioLiteral(expression.type, expression.literal);
    case 'variable':
      return expression.name;
    case 'call':
      return `${expression.name}(${expression.arguments
        .map((argument) => formatExpression(argument))
        .join(', ')})`;
    case 'unary': {
      const operand = formatExpression(expression.operand);
      const text = `${expression.operator}${operand}`;
      return expressionPrecedence(expression.operand) < UNARY_PRECEDENCE
        ? `${expression.operator}(${operand})`
        : text;
    }
    case 'binary': {
      const precedence = BINARY_PRECEDENCE[expression.operator] ?? 6;
      const left = formatExpression(expression.left);
      const right = formatExpression(expression.right);
      const leftText =
        expressionPrecedence(expression.left) < precedence
          ? `(${left})`
          : left;
      // 右操作数在相同优先级时也加括号，保持数据流定义的分组，
      // 避免浮点结合顺序被改变。
      const rightText =
        expressionPrecedence(expression.right) <= precedence
          ? `(${right})`
          : right;
      return `${leftText} ${expression.operator} ${rightText}`;
    }
  }
}

function expressionPrecedence(expression: IrExpression): number {
  switch (expression.kind) {
    case 'literal':
    case 'variable':
    case 'call':
      return ATOM_PRECEDENCE;
    case 'unary':
      return UNARY_PRECEDENCE;
    case 'binary':
      return BINARY_PRECEDENCE[expression.operator] ?? 6;
  }
}
